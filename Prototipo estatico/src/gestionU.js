async function cargarUsuarios(){
    const {data, error} = await _supabase
        .from('perfiles')
        .select('*')

    if(error) console.error('Error:', error.message);
    else{
        console.log(data);
        data.forEach(usu => {
           tblUsuarios.innerHTML = tblUsuarios.innerHTML + 
            `<tr>
            <td>${usu.id}</td>
            <td>${usu.nombre}</td>
            <td>${usu.correo}</td>
            <td>${usu.tipo}</td>
            </tr>` 
        });
    }
}

